//go:build embedui

// Package web embeds the production frontend build (web/dist). Build the
// frontend first (npm run build), then compile with -tags embedui.
package web

import (
	"embed"
	"io/fs"
)

//go:embed all:dist
var dist embed.FS

// FS returns the built UI rooted at dist/.
func FS() fs.FS {
	sub, err := fs.Sub(dist, "dist")
	if err != nil {
		panic(err)
	}
	return sub
}
